function toSignupLanguage(code) {
  const base = String(code || '').toLowerCase().split(/[-_]/)[0];
  return SIGNUP_LANGUAGES.includes(base) ? base : null;
}

function signupCopy(lang) {
  return COPY[toSignupLanguage(lang) || 'en'];
}

function legalCopy(lang) {
  return LEGAL[toSignupLanguage(lang) || 'en'];
}

// The profile draft the talent confirms before the account exists: one line per group, empty parts left out.
function renderDraft(lang, d = {}) {
  const c = signupCopy(lang);
  const has = (v) => v !== null && v !== undefined && String(v).trim() !== '';
  const lines = [
    joinParts([d.name, d.role, d.city]),
    joinParts([has(d.yearsOfExperience) ? c.years(d.yearsOfExperience) : null, d.stack]),
    joinParts([d.languages, d.workMode, has(d.monthlyHours) ? c.hours(d.monthlyHours) : null]),
    has(d.hourlyRate) || has(d.annualRate) ? c.rates(has(d.hourlyRate) ? d.hourlyRate : null, has(d.annualRate) ? d.annualRate : null) : '',
  ].filter(Boolean);
  return [c.draftTitle, ...lines].join('\n');
}

// One role of the main-role step: name, why it fits (source + one fact) and, when known, how many open projects want it.
function renderRole(lang, { name, source, evidence, openProjects, recommended }) {
  const c = signupCopy(lang);
  const reason = c.roleReason[source] || null;
  const why = reason && evidence ? `${reason}: ${evidence}` : reason || evidence || null;
  return [
    recommended ? c.roleRecommended(name) : c.roleName(name),
    why,
    typeof openProjects === 'number' && openProjects > 0 ? c.openProjects(openProjects) : null,
  ].filter(Boolean).join('\n');
}

