function joinParts(parts) {
  return parts.filter((p) => p !== null && p !== undefined && String(p).trim() !== '').join(' · ');
}

function amount(lang, value) {
  return new Intl.NumberFormat(LOCALES[lang], { maximumFractionDigits: 0 }).format(Number(value));
}

